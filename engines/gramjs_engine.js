// ═══════════════════════════════════════════════
//  Entry point
// ═══════════════════════════════════════════════

async function main() {
  try {
    const payload = await readStdinJSON();
    const { action } = payload;

    if (!action) {
      return fail("Missing 'action' field");
    }

    switch (action) {
      case "send_code":
        return await actionSendCode(payload);
      case "verify_code":
        return await actionVerifyCode(payload);
      case "verify_password":
        return await actionVerifyPassword(payload);
      case "credit":
        return success({ credit: CREDIT_FOOTER.trim(), author: AUTHOR });
      default:
        return fail(`Unknown action: ${action}`);
    }
  } catch (err) {
    fail(err.stack || err.message || String(err));
  }
}

main();
