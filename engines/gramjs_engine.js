/**
 * action: "send_code"
 * payload: { phone, api_id, api_hash }
 * returns: { phone_code_hash }
 */
async function actionSendCode(payload) {
  const { phone, api_id, api_hash } = payload;

  const client = new TelegramClient(
    new StringSession(""),
    api_id,
    api_hash,
    {
      connectionRetries: 3,
      deviceModel: "Universal Session Bot",
      systemVersion: "v1.0",
      appVersion: "v1.0",
    }
  );

  await client.connect();

  const result = await client.invoke(
    new (require("telegram/tl/functions/auth").SendCode)({
      phoneNumber: phone,
      apiId: api_id,
      apiHash: api_hash,
      settings: {
        _: "codeSettings",
        allowFlashCall: false,
        currentNumber: false,
        allowAppHash: false,
      },
    })
  );

  // Save session for later steps (in-memory only, caller manages)
  const tempSession = client.session.save();

  await client.disconnect();

  success({
    phone_code_hash: result.phoneCodeHash,
    temp_session: tempSession,
  });
}

/**
 * action: "verify_code"
 * payload: { phone, code, phone_code_hash, api_id, api_hash }
 * returns: { session_string, user_id, dc_id, ... }
 */
async function actionVerifyCode(payload) {
  const { phone, code, phone_code_hash, api_id, api_hash } = payload;

  const client = new TelegramClient(
    new StringSession(""),
    api_id,
    api_hash,
    {
      connectionRetries: 3,
      deviceModel: "Universal Session Bot",
      systemVersion: "v1.0",
      appVersion: "v1.0",
    }
  );

  await client.connect();

  const { SignIn } = require("telegram/tl/functions/auth");

  try {
    await client.invoke(
      new SignIn({
        phoneNumber: phone,
        phoneCodeHash: phone_code_hash,
        phoneCode: code,
      })
    );
  } catch (err) {
    if (
      err.errorMessage === "SESSION_PASSWORD_NEEDED" ||
      String(err).includes("SESSION_PASSWORD_NEEDED")
    ) {
      await client.disconnect();
      return writeJSON({
        success: false,
        needs_password: true,
        author: AUTHOR,
      });
    }
    await client.disconnect();
    throw err;
  }

  const me = await client.getMe();
  const sessionString = client.session.save();

  await client.disconnect();

  success({
    session_string: sessionString,
    user_id: me.id.toString(),
    first_name: me.firstName || "",
    last_name: me.lastName || "",
    username: me.username || "",
    phone: me.phone || phone,
    is_bot: !!me.bot,
  });
}

